/**
 * auto_pwa_init_config: build a ctpwa config.yml from scratch out of a
 * structured spec, with the SAME rendering and the SAME gates as
 * `auto_pwa_edit_config`.
 *
 * Design rules (see PLAN-STEP3.md Part A):
 *   - never a second YAML emitter: the raw document is built as nested Maps and
 *     rendered by `dumpConfig` (config-edit) exactly like an edited config;
 *   - resonances are inserted through `applyResonanceAddition` and checked by
 *     `validateResonanceAddition`, so "create" and "edit" cannot drift;
 *   - the produced text is re-parsed (`parseConfig`) and passed through
 *     `validateConfig` + `crossReferenceErrors` before it is ever written;
 *   - every failure is a structured `ValidationIssue`; a non-empty `errors`
 *     list means the caller must NOT write the file;
 *   - when the spec omits `plot`, a sensible Plot block is generated (one mass
 *     spectrum + one decay-angle distribution per intermediate decay step) so
 *     the fit produces distributions for `auto_pwa_evaluate` to judge.
 *
 * No I/O except an optional Data-file existence check (pass `baseDir`).
 */
import { existsSync } from 'node:fs'
import { isAbsolute, resolve } from 'node:path'
import { applyResonanceAddition, crossReferenceErrors, dumpConfig, parseConfig, rebuildViews, validateConfig } from './config-edit.js'
import { getParticleInfo } from './particle-info.js'
import { validateResonanceAddition } from './resonance-validate.js'
import type {
  InitialConfigResult,
  InitialConfigSpec,
  InitialParticleSpec,
  JP,
  PwaConfig,
  ResonanceProposal,
  ResonanceDb,
  ValidationIssue,
} from './types.js'

/** YAML mappings can have complex (non-string) keys, e.g. `[J: 1, P: -1]`. */
type YamlMap = Map<unknown, unknown>

const err = (code: string, message: string): ValidationIssue => ({ code, message })
const warn = (code: string, message: string): ValidationIssue => ({ code, message })

const round4 = (x: number): number => Math.round(x * 1e4) / 1e4

/**
 * Auto-generate the `Plot` block from the decay chains: for every intermediate
 * decay step, a 1D mass spectrum and a 1D decay-angle distribution.
 *
 * Both are deliberately 1D: `auto_pwa_evaluate` computes pull/chi2 from the
 * 1D mass spectra (the convergence criterion) and Legendre moments from the
 * 1D angular distributions (the "which J is missing" signal). A 2D
 * mass×cosθ entry would give moments only (no binned pull), so it is not
 * generated by default.
 *
 * Ranges: mass ∈ [m(d1)+m(d2), m_mother − m_spectator] (the physically
 * accessible window), cosθ ∈ [−1, 1].
 */
function autoPlotEntries(cfg: PwaConfig): unknown[] {
  const out: unknown[] = []
  const used = new Set<string>()
  const unique = (base: string): string => {
    let name = base
    let i = 2
    while (used.has(name)) name = `${base}_${i++}`
    used.add(name)
    return name
  }
  for (const chain of Object.values(cfg.decayChains)) {
    for (const intName of Object.keys(chain.intermediates)) {
      const kin = cfg.kinematics[intName]
      const steps = chain.steps.filter((s) => s.mother === intName)
      steps.forEach((step, idx) => {
        const [d1, d2] = step.daughters
        if (d1 === undefined || d2 === undefined) return
        const m1 = cfg.particles[d1]?.mass
        const m2 = cfg.particles[d2]?.mass
        const lo = m1 !== undefined && m2 !== undefined ? m1 + m2 : 0
        const hi = kin?.threshold !== undefined && kin.threshold > lo ? kin.threshold : lo + 1
        const suffix = steps.length > 1 ? `_${idx}` : ''

        const mass: YamlMap = new Map()
        mass.set('name', unique(`m_${intName}${suffix}`))
        mass.set('expression', `M([${d1},${d2}])`)
        mass.set('bins', [100])
        mass.set('ranges', [[round4(lo), round4(hi)]])
        mass.set('display', [`M(${d1},${d2}) [GeV]`, 'Events'])
        out.push(mass)

        const angle: YamlMap = new Map()
        angle.set('name', unique(`cosbeta_${intName}${suffix}`))
        angle.set('expression', `CosAngle([${d1}], [${d1},${d2}])`)
        angle.set('bins', [40])
        angle.set('ranges', [[-1, 1]])
        angle.set('display', [`cos#theta(${d1})`, 'Events'])
        out.push(angle)
      })
    }
  }
  return out
}

/** Existence check for the Data samples (relative paths resolve against `baseDir`). */
function checkDataFiles(spec: InitialConfigSpec, baseDir: string): ValidationIssue[] {
  const out: ValidationIssue[] = []
  const samples: [string, unknown[] | undefined][] = [
    ['data', spec.data.data],
    ['phsp', spec.data.phsp],
    ['phsp_truth', spec.data.phspTruth],
    ['bkg', spec.data.bkg],
    ['bkg_weights', spec.data.bkgWeights],
  ]
  for (const [key, sample] of samples) {
    if (sample === undefined) continue
    const p = sample[1]
    if (typeof p !== 'string' || p === '') {
      out.push(warn('data-sample-malformed', `Data.${key}: 样本格式应为 [dat|ROOT, 路径, ...]，当前为 ${JSON.stringify(sample)}`))
      continue
    }
    const abs = isAbsolute(p) ? p : resolve(baseDir, p)
    if (!existsSync(abs)) {
      out.push(warn('data-file-missing', `Data.${key}: 文件不存在 ${abs}（相对路径按分析目录解析）`))
    }
  }
  return out
}

/** [J,P] encoded the way config-edit does (complex YAML key `[{J: j}, {P: p}]`). */
function encodeJpKey(jp: JP): unknown[] {
  return [{ J: jp.j }, { P: jp.p }]
}

function jpText(jp: JP): string {
  return `${jp.j}${jp.p > 0 ? '+' : '-'}`
}

/** Resolve a particle's J/P/mass: explicit fields win, PDGID fills the gaps. */
function resolveParticle(
  spec: InitialParticleSpec,
  db: ResonanceDb | undefined,
): { j?: number; p?: 1 | -1; mass?: number; info?: ReturnType<typeof getParticleInfo>; warnings: ValidationIssue[] } {
  const warnings: ValidationIssue[] = []
  const info = spec.pdgid !== undefined && db !== undefined ? getParticleInfo(db, spec.pdgid) : undefined
  if (spec.pdgid !== undefined && db !== undefined && info === undefined) {
    warnings.push(warn('pdgid-unknown', `Particles.${spec.name}: pdgid ${spec.pdgid} is not in the PDG particle table`))
  }
  let j = spec.j
  let p = spec.p
  let mass = spec.mass
  if (info !== undefined) {
    if (j === undefined) j = info.j
    else if (info.j !== undefined && info.j !== j) {
      warnings.push(warn('pdgid-j-mismatch', `Particles.${spec.name}: J = ${j} but PDGID ${spec.pdgid} (${info.name}) has J = ${info.j}`))
    }
    if (p === undefined) p = info.p
    else if (info.p !== undefined && info.p !== p) {
      warnings.push(warn('pdgid-p-mismatch', `Particles.${spec.name}: P = ${p > 0 ? '+' : '-'} but PDGID ${spec.pdgid} (${info.name}) has P = ${info.p > 0 ? '+' : '-'}`))
    }
    // Mass: explicit wins; otherwise the PDG summary value (absent for
    // neutrinos/photons/K_S/K_L and other states the PDG gives no mass).
    if (mass === undefined && info.mass !== undefined) mass = info.mass
  }
  return { j, p, mass, info, warnings }
}

/**
 * Build a full config from a structured spec.
 *
 * Returns the rendered YAML text only when `errors` is empty; `warnings` are
 * advisory (PDG deviations, missing optional samples, ...).
 */
export function buildInitialConfig(
  spec: InitialConfigSpec,
  db?: ResonanceDb,
  options: {
    resonanceOptions?: Parameters<typeof validateResonanceAddition>[3]
    /** When given, Data sample paths are existence-checked (relative to this dir). */
    baseDir?: string
  } = {},
): InitialConfigResult {
  const errors: ValidationIssue[] = []
  const warnings: ValidationIssue[] = []
  const changed: string[] = []

  // ---- structural checks -------------------------------------------------
  if (spec.particles.length === 0) errors.push(err('no-particles', 'Particles is empty'))

  const particleNames = new Set<string>()
  for (const p of spec.particles) {
    if (particleNames.has(p.name)) errors.push(err('duplicate-particle', `Particles.${p.name} is defined twice`))
    particleNames.add(p.name)
  }

  const chainNames = new Set<string>()
  for (const chain of spec.chains) {
    if (chainNames.has(chain.name)) errors.push(err('duplicate-chain', `DecayChains.${chain.name} is defined twice`))
    chainNames.add(chain.name)

    const intNames = new Set(chain.intermediates.map((i) => i.name))
    for (const i of chain.intermediates) {
      if (i.groups.length === 0) errors.push(err('empty-intermediate', `${chain.name}.${i.name} has no [J,P] group`))
    }
    for (const step of chain.steps) {
      const known = (n: string): boolean => particleNames.has(n) || intNames.has(n)
      if (!known(step.mother)) {
        errors.push(err('unknown-mother', `${chain.name}: step mother "${step.mother}" is neither a Particles entry nor an intermediate of the chain`))
      }
      for (const d of step.daughters) {
        if (!known(d)) {
          errors.push(err('unknown-daughter', `${chain.name}: step ${step.mother} -> ${step.daughters.join(' + ')}: daughter "${d}" is neither a Particles entry nor an intermediate of the chain`))
        }
      }
    }
    // Every intermediate must be reachable from some step (as mother or daughter).
    const mentioned = new Set<string>()
    for (const s of chain.steps) {
      mentioned.add(s.mother)
      for (const d of s.daughters) mentioned.add(d)
    }
    for (const i of chain.intermediates) {
      if (!mentioned.has(i.name)) {
        warnings.push(warn('unused-intermediate', `${chain.name}.${i.name} is declared but never appears in a decay step`))
      }
    }
  }

  // ---- Data --------------------------------------------------------------
  if (spec.data.order.length === 0) errors.push(err('data-order-empty', 'Data.order is empty'))
  for (const o of spec.data.order) {
    if (!particleNames.has(o)) errors.push(err('data-order-unknown', `Data.order lists "${o}" but it is not in Particles`))
  }
  if (spec.data.data.length === 0) errors.push(err('data-missing', 'Data.data is required'))
  if (spec.data.phsp === undefined || spec.data.phsp.length === 0) {
    warnings.push(warn('phsp-missing', 'Data.phsp is not set — ctpwa needs phase-space MC for a normalised fit'))
  }
  if (options.baseDir !== undefined) warnings.push(...checkDataFiles(spec, options.baseDir))

  // ---- Particles (resolve J/P/mass, collect warnings) --------------------
  const resolved = new Map<string, { j?: number; p?: 1 | -1; mass?: number }>()
  for (const p of spec.particles) {
    const r = resolveParticle(p, db)
    warnings.push(...r.warnings)
    if (r.j === undefined) errors.push(err('missing-j', `Particles.${p.name}: J is required (give it explicitly or via pdgid)`))
    if (r.p === undefined) errors.push(err('missing-p', `Particles.${p.name}: P is required (give it explicitly or via pdgid)`))
    if (r.mass === undefined) errors.push(err('missing-mass', `Particles.${p.name}: mass is required (give it explicitly or via pdgid)`))
    resolved.set(p.name, { j: r.j, p: r.p, mass: r.mass })
  }

  // ---- Resonances (structural: chain/group must exist) -------------------
  const proposals: ResonanceProposal[] = []
  for (const r of spec.resonances ?? []) {
    const chain = spec.chains.find((c) => c.intermediates.some((i) => i.name === r.chain))
    if (chain === undefined) {
      errors.push(err('unknown-chain', `Resonances.${r.name}: no intermediate "${r.chain}" in any chain`))
      continue
    }
    const int = chain.intermediates.find((i) => i.name === r.chain)!
    if (!int.groups.some((g) => g.j === r.jpGroup.j && g.p === r.jpGroup.p)) {
      errors.push(err('unknown-jp-group', `Resonances.${r.name}: ${r.chain} has no [${jpText(r.jpGroup)}] group (declare it in chains[].intermediates[].groups)`))
      continue
    }
    proposals.push(r)
  }

  if (errors.length > 0) return { changed, errors, warnings }

  // ---- build the raw YAML document ---------------------------------------
  const raw: YamlMap = new Map()

  if (spec.precision !== undefined && spec.precision !== '') raw.set('precision', spec.precision)

  const particlesRaw: YamlMap = new Map()
  for (const p of spec.particles) {
    const r = resolved.get(p.name)!
    const props: YamlMap = new Map()
    props.set('J', r.j)
    props.set('P', r.p)
    props.set('mass', r.mass)
    if (p.pdgid !== undefined) props.set('pdgid', p.pdgid)
    if (p.c !== undefined) props.set('c', p.c)
    props.set('tex', [p.tex ?? `\\mathrm{${p.name}}`])
    particlesRaw.set(p.name, props)
  }
  raw.set('Particles', particlesRaw)

  const dataRaw: YamlMap = new Map()
  dataRaw.set('order', [...spec.data.order])
  dataRaw.set('data', spec.data.data)
  if (spec.data.phsp !== undefined) dataRaw.set('phsp', spec.data.phsp)
  if (spec.data.phspTruth !== undefined) dataRaw.set('phsp_truth', spec.data.phspTruth)
  if (spec.data.bkg !== undefined) dataRaw.set('bkg', spec.data.bkg)
  if (spec.data.bkgWeights !== undefined) dataRaw.set('bkg_weights', spec.data.bkgWeights)
  raw.set('Data', dataRaw)

  const chainsRaw: YamlMap = new Map()
  for (const chain of spec.chains) {
    const chainRaw: YamlMap = new Map()
    // Group the steps by mother so a production particle with several
    // intermediate partners becomes one compact `Mother: [[d1, R1], [d2, R2]]`.
    const byMother = new Map<string, unknown[]>()
    for (const step of chain.steps) {
      const mode: unknown[] = [step.daughters[0], step.daughters[1]]
      const opts: YamlMap = new Map()
      if (step.sl !== undefined) opts.set('sl', step.sl)
      if (step.pBreak !== undefined) opts.set('p_break', step.pBreak)
      if (step.hasBf !== undefined) opts.set('has_bf', step.hasBf)
      if (step.bfD !== undefined) opts.set('bf_d', step.bfD)
      if (opts.size > 0) mode.push(opts)
      const list = byMother.get(step.mother) ?? []
      list.push(mode)
      byMother.set(step.mother, list)
    }
    for (const [mother, modes] of byMother) {
      // A single mode is written flat ([d1, d2]); several as a mode list.
      chainRaw.set(mother, modes.length === 1 ? (modes[0] as unknown[]) : modes)
    }
    const intermediatesRaw: YamlMap = new Map()
    for (const int of chain.intermediates) {
      const groupList: unknown[] = []
      for (const jp of int.groups) {
        const group: YamlMap = new Map()
        group.set(encodeJpKey(jp), []) // empty: resonances are attached (and gated) below
        groupList.push(group)
      }
      intermediatesRaw.set(int.name, groupList)
    }
    chainRaw.set('intermediates', intermediatesRaw)
    chainsRaw.set(chain.name, chainRaw)
  }
  raw.set('DecayChains', chainsRaw)

  const constraintsRaw: YamlMap = new Map()
  const c = spec.constraints
  if (c !== undefined) {
    if (c.identical !== undefined) constraintsRaw.set('identical', c.identical)
    if (c.trans !== undefined) constraintsRaw.set('trans', c.trans.map((t) => new Map([[t.names, t.value]])))
    if (c.maxL !== undefined) constraintsRaw.set('maxL', c.maxL)
    if (c.bfD !== undefined) constraintsRaw.set('bf_d', c.bfD)
    if (c.hasBf !== undefined) constraintsRaw.set('has_bf', c.hasBf)
    if (c.fixVar !== undefined) constraintsRaw.set('fix_var', c.fixVar)
    if (c.freeVar !== undefined) constraintsRaw.set('free_var', c.freeVar)
    if (c.varRange !== undefined) constraintsRaw.set('var_range', c.varRange)
    if (c.varEqual !== undefined) constraintsRaw.set('var_equal', c.varEqual)
    if (c.gaussConstr !== undefined) constraintsRaw.set('gauss_constr', c.gaussConstr)
  }
  raw.set('Constraints', constraintsRaw)

  raw.set('Resonances', new Map())

  if (spec.plot !== undefined && spec.plot.length > 0) {
    const plotList: unknown[] = spec.plot.map((pl) => {
      const item: YamlMap = new Map()
      if (pl.name !== undefined) item.set('name', pl.name)
      item.set('expression', pl.expression)
      if (pl.bins !== undefined) item.set('bins', pl.bins)
      if (pl.ranges !== undefined) item.set('ranges', pl.ranges)
      if (pl.display !== undefined) item.set('display', pl.display)
      return item
    })
    raw.set('Plot', plotList)
  }

  // ---- render + round-trip ----------------------------------------------
  let config: PwaConfig = { raw, ...rebuildViews(raw) }
  // Plot: an explicit list wins; `plot: []` opts out; omitted -> auto-generate
  // (without distributions the fit output has nothing for auto_pwa_evaluate).
  if (spec.plot === undefined) {
    const auto = autoPlotEntries(config)
    if (auto.length > 0) {
      raw.set('Plot', auto)
      changed.push(`Plot: 自动生成 ${auto.length} 个 1D 分布（每个中间态衰变步一个质量谱 + 一个 cosθ 谱）`)
    }
  }
  let text: string
  try {
    text = dumpConfig(config)
  } catch (e) {
    return { changed, errors: [err('render-failed', `dumpConfig failed: ${(e as Error).message}`)], warnings }
  }
  try {
    config = parseConfig(text)
  } catch (e) {
    return { changed, errors: [err('roundtrip-failed', `rendered config is not parseable: ${(e as Error).message}`)], warnings }
  }

  // ---- attach resonances through the edit gate ---------------------------
  for (const proposal of proposals) {
    if (db !== undefined) {
      const v = validateResonanceAddition(db, config, proposal, options.resonanceOptions)
      warnings.push(...v.warnings)
      if (!v.ok) {
        errors.push(...v.errors.map((e) => err(e.code, `Resonances.${proposal.name}: ${e.message}`)))
        continue
      }
    }
    const applied = applyResonanceAddition(config, proposal)
    if (applied.errors.length > 0) {
      errors.push(...applied.errors.map((e) => err(e.code, `Resonances.${proposal.name}: ${e.message}`)))
      continue
    }
    config = applied.config
    changed.push(...applied.changed)
  }

  // ---- final gates -------------------------------------------------------
  const v = validateConfig(config, db)
  errors.push(...v.errors)
  warnings.push(...v.warnings)
  const xref = crossReferenceErrors(config)
  errors.push(...xref.errors)
  warnings.push(...xref.warnings)

  if (errors.length > 0) return { config, changed, errors, warnings }

  try {
    text = dumpConfig(config)
  } catch (e) {
    return { config, changed, errors: [err('render-failed', `dumpConfig failed: ${(e as Error).message}`)], warnings }
  }
  changed.unshift(
    `Particles: ${spec.particles.length} 个`,
    `DecayChains: ${spec.chains.map((c2) => c2.name).join(', ')}`,
    `Resonances: ${proposals.length} 个`,
  )
  return { text, config, changed, errors, warnings }
}
