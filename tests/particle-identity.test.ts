describe('validateConfig: PDGID consistency', () => {
  const base = (particles: string, extra = '') => `Particles:
${particles}
DecayChains:
  decay1:
    Jpsi: [[Kp, R_KK]]
    R_KK: [Kp, Km]
    intermediates:
      R_KK:
        - [J: 1, P: -1]: [phi1020]
${extra}Resonances:
  phi1020: {J: 1, P: -1, model: BWR, parameters: [1.0195, 0.0045]}
`
  const JPSI = '  Jpsi: {J: 1, P: -1, mass: 3.0969, pdgid: 443}'
  const KP = '  Kp: {J: 0, P: -1, mass: 0.4937, pdgid: 321}'
  const KM = '  Km: {J: 0, P: -1, mass: 0.4937, pdgid: -321}'

  it('a clean PDGID config produces no PDGID warnings', () => {
    const v = validateConfig(parseConfig(base(`${JPSI}\n${KP}\n${KM}`)), defaultDb)
    expect(v.errors).toEqual([])
    expect(v.warnings.filter((w) => w.code.startsWith('pdgid') || w.code.startsWith('identical'))).toEqual([])
  })

  it('unknown PDGID -> pdgid-unknown warning', () => {
    const v = validateConfig(parseConfig(base(`${JPSI}\n  Kp: {J: 0, P: -1, mass: 0.4937, pdgid: 999999}\n${KM}`)), defaultDb)
    expect(v.warnings.map((w) => w.code)).toContain('pdgid-unknown')
  })

  it('J / P mismatch against the PDGID -> warnings', () => {
    const v = validateConfig(parseConfig(base(`${JPSI}\n  Kp: {J: 1, P: 1, mass: 0.4937, pdgid: 321}\n${KM}`)), defaultDb)
    const codes = v.warnings.map((w) => w.code)
    expect(codes).toContain('pdgid-j-mismatch')
    expect(codes).toContain('pdgid-p-mismatch')
  })

  it('an explicit C on a non-eigenstate -> pdgid-c-not-eigenstate warning', () => {
    const v = validateConfig(parseConfig(base(`${JPSI}\n  Kp: {J: 0, P: -1, mass: 0.4937, pdgid: 321, c: -1}\n${KM}`)), defaultDb)
    expect(v.warnings.map((w) => w.code)).toContain('pdgid-c-not-eigenstate')
  })

  it('same-PDGID daughters not declared identical -> identical-missing (the pi01/pi02 hole)', () => {
    const cfg = parseConfig(`Particles:
  Jpsi: {J: 1, P: -1, mass: 3.0969, pdgid: 443}
  pi01: {J: 0, P: -1, mass: 0.1350, pdgid: 111}
  pi02: {J: 0, P: -1, mass: 0.1350, pdgid: 111}
DecayChains:
  decay1:
    Jpsi: [[pi01, R_pipi]]
    R_pipi: [pi01, pi02]
    intermediates:
      R_pipi:
        - [J: 2, P: 1]: [f2_1270]
Resonances:
  f2_1270: {J: 2, P: 1, model: BWR, parameters: [1.275, 0.185]}
`)
    const v = validateConfig(cfg, defaultDb)
    const hit = v.warnings.find((w) => w.code === 'identical-missing')
    expect(hit).toBeDefined()
    expect(hit!.message).toContain('pi01')
    expect(hit!.message).toContain('111')
  })

  it('declaring the identical group silences identical-missing', () => {
    const cfg = parseConfig(`Particles:
  Jpsi: {J: 1, P: -1, mass: 3.0969, pdgid: 443}
  pi01: {J: 0, P: -1, mass: 0.1350, pdgid: 111}
  pi02: {J: 0, P: -1, mass: 0.1350, pdgid: 111}
Constraints:
  identical:
    - [pi01, pi02]
DecayChains:
  decay1:
    Jpsi: [[pi01, R_pipi]]
    R_pipi: [pi01, pi02]
    intermediates:
      R_pipi:
        - [J: 2, P: 1]: [f2_1270]
Resonances:
  f2_1270: {J: 2, P: 1, model: BWR, parameters: [1.275, 0.185]}
`)
    const v = validateConfig(cfg, defaultDb)
    expect(v.warnings.map((w) => w.code)).not.toContain('identical-missing')
  })

  it('declaring K0/Kbar0 as identical -> identical-pdgid-mismatch warning', () => {
    const cfg = parseConfig(`Particles:
  Jpsi: {J: 1, P: -1, mass: 3.0969, pdgid: 443}
  K01: {J: 0, P: -1, mass: 0.4976, pdgid: 311}
  K02: {J: 0, P: -1, mass: 0.4976, pdgid: -311}
Constraints:
  identical:
    - [K01, K02]
DecayChains:
  decay1:
    Jpsi: [[K01, R_KK]]
    R_KK: [K01, K02]
    intermediates:
      R_KK:
        - [J: 1, P: -1]: [phi1020]
Resonances:
  phi1020: {J: 1, P: -1, model: BWR, parameters: [1.0195, 0.0045]}
`)
    expect(validateConfig(cfg, defaultDb).warnings.map((w) => w.code)).toContain('identical-pdgid-mismatch')
  })

  it('without a db the PDGID checks are skipped (backward compatible)', () => {
    const cfg = parseConfig(`Particles:
  Jpsi: {J: 1, P: -1, mass: 3.0969, pdgid: 999999}
DecayChains:
  decay1:
    Jpsi: [[Jpsi, R_KK]]
    R_KK: [Jpsi, Jpsi]
    intermediates:
      R_KK:
        - [J: 1, P: -1]: [phi1020]
Resonances:
  phi1020: {J: 1, P: -1, model: BWR, parameters: [1.0195, 0.0045]}
`)
    const v = validateConfig(cfg)
    expect(v.warnings.map((w) => w.code)).not.toContain('pdgid-unknown')
  })
})

