// pairJPC: C sets at the decay vertex
// ---------------------------------------------------------------------------
describe('pairJPC: C sets with PDGID', () => {
  const Kp = { name: 'Kp', j: 0, p: -1 as const, pdgid: 321 }
  const Km = { name: 'Km', j: 0, p: -1 as const, pdgid: -321 }

  it('K+K- carries C = (-1)^L: 1--, 2++, 3-- are all realizable', () => {
    const waves = pairJPC(Kp, Km, { maxL: 3, db: defaultDb })
    const labels = waves.map((w) => `${w.jpc.j}${w.jpc.p > 0 ? '+' : '-'}${w.jpc.c! > 0 ? '+' : '-'}`)
    expect(labels).toEqual(['0++', '1--', '2++', '3--'])
  })

  it('without a db the same result comes from the name table (regression)', () => {
    const a = pairJPC(Kp, Km, { maxL: 3, db: defaultDb }).map((w) => w.jpc)
    const b = pairJPC({ name: 'Kp', j: 0, p: -1 }, { name: 'Km', j: 0, p: -1 }, { maxL: 3 }).map((w) => w.jpc)
    expect(b).toEqual(a)
  })

  it('two pi0 declared identical see only even L (Bose rule) with C=+1', () => {
    const waves = pairJPC(
      { name: 'pi01', j: 0, p: -1, pdgid: 111 },
      { name: 'pi02', j: 0, p: -1, pdgid: 111 },
      { maxL: 4, identicalGroups: [['pi01', 'pi02']], db: defaultDb },
    )
    for (const w of waves) {
      expect(w.jpc.c).toBe(1)
      expect(w.sl.every((s) => s.l % 2 === 0)).toBe(true)
    }
    expect(waves.map((w) => w.jpc.j)).toEqual([0, 2, 4])
  })

  it('two Lambdas declared identical obey the Fermi rule (-1)^(L+S) = -1, C = -1', () => {
    const waves = pairJPC(
      { name: 'L1', j: 0.5, p: 1, pdgid: 3122 },
      { name: 'L2', j: 0.5, p: 1, pdgid: 3122 },
      { maxL: 3, identicalGroups: [['L1', 'L2']], db: defaultDb },
    )
    expect(waves.length).toBeGreaterThan(0)
    for (const w of waves) {
      expect(w.jpc.c).toBe(-1)
      for (const { s, l } of w.sl) {
        const S = (s - 1) / 2 // s is 2S+1
        // identical fermions: (-1)^(L+S) = -1
        expect((l + S) % 2).toBe(1)
      }
    }
  })

  it('without the identical declaration the same Lambda pair is NOT symmetrised', () => {
    const waves = pairJPC(
      { name: 'L1', j: 0.5, p: 1, pdgid: 3122 },
      { name: 'L2', j: 0.5, p: 1, pdgid: 3122 },
      { maxL: 1, db: defaultDb },
    )
    // same PDGID but no group -> engine treats them as distinct, C undefined
    expect(waves.every((w) => w.jpc.c === undefined)).toBe(true)
  })
})

