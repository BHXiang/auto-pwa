describe('deriveIdenticalGroups', () => {
  it('merges same-PDGID daughters of a step (3-body pi0 case)', () => {
    const cfg = parseConfig(`Particles:
  Jpsi: {J: 1, P: -1, mass: 3.0969, pdgid: 443}
  pi01: {J: 0, P: -1, mass: 0.1350, pdgid: 111}
  pi02: {J: 0, P: -1, mass: 0.1350, pdgid: 111}
  pi03: {J: 0, P: -1, mass: 0.1350, pdgid: 111}
DecayChains:
  decay1:
    Jpsi: [[pi01, R_pipi]]
    R_pipi: [pi02, pi03]
    intermediates:
      R_pipi:
        - [J: 2, P: 1]: [f2_1270]
Resonances:
  f2_1270: {J: 2, P: 1, model: BWR, parameters: [1.275, 0.185]}
`)
    // Union-find only merges daughters that share a step; pi01 shares a step
    // with R_pipi (an intermediate), not with pi02/pi03.
    expect(deriveIdenticalGroups(cfg, defaultDb)).toEqual([['pi02', 'pi03']])
  })

  it('no PDGID -> no derivation (legacy configs keep manual declarations)', () => {
    const cfg = parseConfig(`Particles:
  Kp: {J: 0, P: -1, mass: 0.4937}
  Km: {J: 0, P: -1, mass: 0.4937}
DecayChains:
  decay1:
    Jpsi: [[Kp, R_KK]]
    R_KK: [Kp, Km]
    intermediates:
      R_KK:
        - [J: 1, P: -1]: [phi1020]
Resonances:
  phi1020: {J: 1, P: -1, model: BWR, parameters: [1.0195, 0.0045]}
`)
    expect(deriveIdenticalGroups(cfg, defaultDb)).toEqual([])
  })
})

