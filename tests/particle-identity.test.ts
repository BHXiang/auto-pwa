// C eigenstate predicate
// ---------------------------------------------------------------------------
describe('C eigenstate predicate', () => {
  it('self-conjugate states with a definite PDG C are eigenstates', () => {
    for (const id of [111, 221, 331, 113, 223, 333, 443, 225, 115, 22]) {
      expect(isCEigenstate(info(id)!)).toBe(true)
      expect(cValueOf(info(id)!)).toBe(info(id)!.c)
    }
  })

  it('charged / flavoured states are not C eigenstates', () => {
    for (const id of [321, -321, 211, -211, 310, 130, 311, -311, 313, 323, 2212, -2212, 3122, -3122, 3334]) {
      expect(isCEigenstate(info(id)!)).toBe(false)
      expect(cValueOf(info(id)!)).toBeUndefined()
    }
  })

  it('TRAP: a charged multiplet member must not pass on the PDG quantum_c value', () => {
    // The PDG sqlite rows for rho(770)+ / a_2(1320)+ where C is meaningless.
    // The generator drops `c` for non-'S' entries, so the predicate stays false.
    for (const id of [213, -213, 215, -215]) {
      const e = info(id)
      expect(e).toBeDefined()
      expect(e!.selfConjugate).toBe(false)
      expect(e!.c).toBeUndefined()
      expect(isCEigenstate(e!)).toBe(false)
    }
  })

  it('TRAP: an unknown ("?") PDG entry is never treated as a C value', () => {
    const e = info(100323) // K(3100)+ family carries '?' quantum numbers
    if (e !== undefined) {
      expect(e.c).toBeUndefined()
      expect(isCEigenstate(e)).toBe(false)
    }
  })
})

