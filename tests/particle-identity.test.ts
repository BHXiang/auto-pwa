describe('resolveC: production-vertex C', () => {
  it('uses the PDGID when present', () => {
    expect(resolveC(defaultDb, { name: 'whatever', pdgid: 443 })).toBe(-1)
    expect(resolveC(defaultDb, { name: 'whatever', pdgid: 221 })).toBe(1)
    expect(resolveC(defaultDb, { name: 'whatever', pdgid: 225 })).toBe(1)
  })

  it('a non-eigenstate PDGID never falls back to a name guess', () => {
    // The PDGID says K+ (no C); the name "phi1020" would have given C=-1.
    expect(resolveC(defaultDb, { name: 'phi1020', pdgid: 321 })).toBeUndefined()
    expect(resolveC(defaultDb, { name: 'Kp', pdgid: 321 })).toBeUndefined()
    expect(resolveC(defaultDb, { name: 'pbar', pdgid: -2212 })).toBeUndefined()
  })

  it('an explicit config c wins', () => {
    expect(resolveC(defaultDb, { pdgid: 321, c: -1 })).toBe(-1)
  })

  it('falls back to the historical name lookup without a PDGID', () => {
    expect(resolveC(defaultDb, { name: 'Jpsi' })).toBe(-1)
    expect(resolveC(defaultDb, { name: 'phi1020' })).toBe(-1)
    expect(resolveC(defaultDb, { name: 'Kp' })).toBeUndefined()
  })

  it('resolveIdentity exposes the antiparticle', () => {
    const id = resolveIdentity(defaultDb, { pdgid: 321 })!
    expect(id.conjugatePdgid).toBe(-321)
    expect(id.conjugateName).toBe('K-')
    const self = resolveIdentity(defaultDb, { pdgid: 333 })!
    expect(self.conjugatePdgid).toBe(333)
    expect(self.conjugateName).toBe('phi(1020)0')
    expect(self.c).toBe(-1)
  })

  it('particleKey keeps the antiparticle mark', () => {
    expect(particleKey('K0')).not.toBe(particleKey('K~0'))
    expect(particleKey('Kp')).toBe(particleKey('K+'))
  })
})

