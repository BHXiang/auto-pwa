describe('classifyPairPhysics: mesons', () => {
  const Kp = { name: 'Kp', pdgid: 321 }
  const Km = { name: 'Km', pdgid: -321 }
  const pi0a = { name: 'pi01', pdgid: 111 }
  const pi0b = { name: 'pi02', pdgid: 111 }
  const pip = { name: 'pip', pdgid: 211 }
  const pim = { name: 'pim', pdgid: -211 }

  it('K+ K- is a conjugate pair, not identical', () => {
    const r = classifyPairPhysics(defaultDb, Kp, Km)
    expect(r).toMatchObject({ identical: false, conjugate: true, cDefined: true, source: 'pdgid' })
  })

  it('pi+ pi- is a conjugate pair', () => {
    expect(classifyPairPhysics(defaultDb, pip, pim)).toMatchObject({ conjugate: true, cDefined: true })
  })

  it('two pi0 with DIFFERENT analysis names are identical (same PDGID)', () => {
    expect(classifyPairPhysics(defaultDb, pi0a, pi0b)).toMatchObject({
      identical: true,
      conjugate: false,
      cDefined: true,
      source: 'pdgid',
    })
  })

  it('K+ K+ is identical (boson), not a conjugate pair', () => {
    const r = classifyPairPhysics(defaultDb, Kp, { name: 'Kp2', pdgid: 321 })
    expect(r).toMatchObject({ identical: true, conjugate: false, cDefined: true })
  })

  it('TRAP: K0 vs Kbar0 are a conjugate pair even when named K01/K02', () => {
    const r = classifyPairPhysics(defaultDb, { name: 'K01', pdgid: 311 }, { name: 'K02', pdgid: -311 })
    expect(r).toMatchObject({ identical: false, conjugate: true, cDefined: true })
    // A name-only heuristic would have grouped K01/K02 as "the same K".
  })

  it('K(S)0 K(S)0 is identical (no C from the table, but the Bose rule applies)', () => {
    const r = classifyPairPhysics(defaultDb, { name: 'Ks1', pdgid: 310 }, { name: 'Ks2', pdgid: 310 })
    expect(r).toMatchObject({ identical: true, conjugate: false, cDefined: true })
    // The individual K(S)0 has no C, but the identical selection rule defines the pair C.
    expect(cValueOf(info(310)!)).toBeUndefined()
  })

  it('pi0 pi+ has no identity relation: no C', () => {
    expect(classifyPairPhysics(defaultDb, pi0a, pip)).toMatchObject({
      identical: false,
      conjugate: false,
      cDefined: false,
      source: 'pdgid',
    })
  })

  it('falls back to the name table when no PDGID is given (legacy configs)', () => {
    const r = classifyPairPhysics(defaultDb, { name: 'Kp' }, { name: 'Km' })
    expect(r).toMatchObject({ conjugate: true, cDefined: true, source: 'name-table' })
    expect(classifyPairPhysics(defaultDb, { name: 'Kp' }, { name: 'Kp2' })).toMatchObject({
      conjugate: false,
      source: 'none',
    })
  })
})

