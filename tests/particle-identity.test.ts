describe('PDG particle table: baryons', () => {
  it('nucleons: p/pbar, n/nbar, with the fermion antiparticle parity sign', () => {
    expect(info(2212)).toMatchObject({ name: 'p', selfConjugate: false, j: 0.5, p: 1, conjugate: -2212 })
    expect(info(-2212)).toMatchObject({ name: 'pbar', ccType: 'A', j: 0.5, p: -1, conjugate: 2212 })
    expect(info(2112)).toMatchObject({ name: 'n', j: 0.5, p: 1, conjugate: -2112 })
    expect(info(-2112)).toMatchObject({ name: 'nbar', j: 0.5, p: -1 })
    // Baryons are never C eigenstates
    expect(info(2212)!.c).toBeUndefined()
    expect(cValueOf(info(2212)!)).toBeUndefined()
  })

  it('hyperons: Lambda / Sigma / Xi / Omega', () => {
    expect(info(3122)).toMatchObject({ name: 'Lambda0', j: 0.5, p: 1, conjugate: -3122 })
    expect(info(-3122)).toMatchObject({ name: 'Lambdabar0', j: 0.5, p: -1, conjugate: 3122 })
    expect(info(3222)).toMatchObject({ name: 'Sigma+', conjugate: -3222 })
    expect(info(3112)).toMatchObject({ name: 'Sigma-', conjugate: -3112 })
    expect(info(3312)).toMatchObject({ name: 'Xi-', conjugate: -3312 })
    expect(info(3322)).toMatchObject({ name: 'Xi0', conjugate: -3322 })
    expect(info(3334)).toMatchObject({ name: 'Omega-', j: 1.5, p: 1, conjugate: -3334 })
    for (const id of [3122, -3122, 3222, 3112, 3312, 3322, 3334]) {
      expect(cValueOf(info(id)!)).toBeUndefined()
    }
  })

  it('the antiparticle of a baryon is found through the table', () => {
    expect(conjugatePdgidOf(defaultDb, 2212)).toBe(-2212)
    expect(conjugatePdgidOf(defaultDb, -2212)).toBe(2212)
    expect(conjugatePdgidOf(defaultDb, 3122)).toBe(-3122)
    // self-conjugate: the conjugate of the PDGID is itself
    expect(conjugatePdgidOf(defaultDb, 111)).toBe(111)
    expect(conjugatePdgidOf(defaultDb, 443)).toBe(443)
    // no distinct antiparticle block
    expect(conjugatePdgidOf(defaultDb, 310)).toBeUndefined()
  })
})

