describe('pdgid survives the config round-trip and edits', () => {
  const CFG = `Particles:
  Jpsi: {J: 1, P: -1, mass: 3.0969, pdgid: 443}
  Kp: {J: 0, P: -1, mass: 0.4937, pdgid: 321}
  Km: {J: 0, P: -1, mass: 0.4937, pdgid: -321}
DecayChains:
  decay1:
    Jpsi: [[Kp, R_KK]]
    R_KK: [Kp, Km]
    intermediates:
      R_KK:
        - [J: 1, P: -1]: [phi1020]
Resonances:
  phi1020: {J: 1, P: -1, model: BWR, parameters: [1.0195, 0.0045]}
`

  it('parse -> dump -> parse keeps every pdgid', () => {
    const cfg = parseConfig(CFG)
    expect(cfg.particles['Kp']!.pdgid).toBe(321)
    expect(cfg.particles['Km']!.pdgid).toBe(-321)
    expect(cfg.particles['Jpsi']!.pdgid).toBe(443)

    const round = parseConfig(dumpConfig(cfg))
    expect(round.particles['Kp']!.pdgid).toBe(321)
    expect(round.particles['Km']!.pdgid).toBe(-321)
    expect(round.particles['Jpsi']!.pdgid).toBe(443)
  })

  it('adding a resonance keeps the particles untouched', () => {
    const applied = applyResonanceAddition(parseConfig(CFG), {
      name: 'rho1700',
      chain: 'R_KK',
      jpGroup: { j: 1, p: -1 },
      model: 'BWR',
      parameters: [1.72, 0.25],
    })
    expect(applied.errors).toEqual([])
    expect(applied.config.particles['Kp']!.pdgid).toBe(321)
    expect(applied.config.particles['Km']!.pdgid).toBe(-321)
    expect(parseConfig(dumpConfig(applied.config)).particles['Km']!.pdgid).toBe(-321)
  })
})
