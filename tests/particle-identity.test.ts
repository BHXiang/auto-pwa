/**
 * PDGID-driven particle identity: meson + baryon validation.
 *
 * The particle table is generated by scripts/fetch_pdg.py from the PDG sqlite
 * (`mcid` = the signed Monte-Carlo ID; `cc_type` = P/A/S). These tests pin the
 * physics the tooling relies on, including the two data traps:
 *   1. the PDG `quantum_c` column also carries spurious C on charged multiplet
 *      members (rho(770)+ -> '-') — `selfConjugate` must be the gate;
 *   2. K(S)0/K(L)0 have no distinct antiparticle block (the API raises).
 */

const info = (pdgid: number) => getParticleInfo(defaultDb, pdgid)

// ---------------------------------------------------------------------------
// Meson sector
// ---------------------------------------------------------------------------
describe('PDG particle table: mesons', () => {
  it('pseudoscalar mesons: pi/K/eta', () => {
    expect(info(111)).toMatchObject({ name: 'pi0', ccType: 'S', selfConjugate: true, j: 0, p: -1, c: 1, g: -1 })
    expect(info(-111)).toBeUndefined() // pi0 is its own antiparticle; no -111 row
    expect(info(211)).toMatchObject({ name: 'pi+', selfConjugate: false, charge: 1, conjugate: -211 })
    expect(info(-211)).toMatchObject({ name: 'pi-', ccType: 'A', charge: -1, conjugate: 211 })
    expect(info(221)).toMatchObject({ name: 'eta', selfConjugate: true, c: 1, g: 1 })
    expect(info(331)).toMatchObject({ name: "eta^'(958)0", selfConjugate: true, c: 1 })
  })

  it('kaons: K+/K- are a conjugate pair, K(S)0/K(L)0 have no antiparticle block', () => {
    expect(info(321)).toMatchObject({ name: 'K+', selfConjugate: false, j: 0, p: -1, conjugate: -321 })
    expect(info(-321)).toMatchObject({ name: 'K-', ccType: 'A', conjugate: 321 })
    expect(info(321)!.c).toBeUndefined()
    // K(S)0 / K(L)0: cc_type 'P' with NO conjugate (the API raises looking up -310)
    expect(info(310)).toMatchObject({ name: 'K(S)0', selfConjugate: false })
    expect(info(310)!.c).toBeUndefined()
    expect(info(310)!.conjugate).toBeUndefined()
    expect(info(130)).toMatchObject({ name: 'K(L)0', selfConjugate: false })
    // Neutral kaons K0/Kbar0 ARE a conjugate pair
    expect(info(311)).toMatchObject({ name: 'K0', conjugate: -311 })
    expect(info(-311)).toMatchObject({ name: 'Kbar0', conjugate: 311 })
  })

  it('vector mesons: rho/omega/phi/K*/J-psi', () => {
    expect(info(113)).toMatchObject({ name: 'rho(770)0', selfConjugate: true, j: 1, p: -1, c: -1, g: 1 })
    expect(info(223)).toMatchObject({ name: 'omega(782)0', selfConjugate: true, c: -1, g: -1 })
    expect(info(333)).toMatchObject({ name: 'phi(1020)0', selfConjugate: true, c: -1, g: -1 })
    expect(info(443)).toMatchObject({ name: 'J/psi(1S)', selfConjugate: true, c: -1 })
    expect(info(313)).toMatchObject({ name: 'K^*(892)0', selfConjugate: false, conjugate: -313 })
    expect(info(323)).toMatchObject({ name: 'K^*(892)+', selfConjugate: false, j: 1, p: -1, conjugate: -323 })
    expect(info(313)!.c).toBeUndefined()
  })

  it('tensor mesons: f2(1270)/a2(1320) are C=+1 eigenstates', () => {
    expect(info(225)).toMatchObject({ name: 'f_2(1270)0', selfConjugate: true, j: 2, p: 1, c: 1, g: 1 })
    expect(info(115)).toMatchObject({ name: 'a_2(1320)0', selfConjugate: true, j: 2, p: 1, c: 1 })
  })

  it('heavy flavoured mesons: D/B', () => {
    expect(info(411)).toMatchObject({ name: 'D+', conjugate: -411 })
    expect(info(-411)).toMatchObject({ name: 'D-', conjugate: 411 })
    expect(info(421)).toMatchObject({ name: 'D0', conjugate: -421 })
    expect(info(521)).toMatchObject({ name: 'B+', conjugate: -521 })
    expect(info(511)).toMatchObject({ name: 'B0', conjugate: -511 })
  })

  it('photon is a C=-1 eigenstate', () => {
    expect(info(22)).toMatchObject({ name: 'gamma', selfConjugate: true, c: -1 })
  })
})

